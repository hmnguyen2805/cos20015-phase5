# COS20015 Phase-05: create (or reset) the three MySQL logins the PHP app uses,
# and write their passwords into app\config\config.php.
#
# Passwords are random, are sent to mysql.exe on standard input (not on the
# command line, so they do not show in the process list) and are never printed.
# Re-running this script simply rotates all three passwords.
#
# Usage (from the phase5 folder):  powershell -ExecutionPolicy Bypass -File scripts\setup_app_accounts.ps1
param([string]$LoginPath = 'claude')

$ErrorActionPreference = 'Stop'
$phase5 = Split-Path -Parent $PSScriptRoot
$mysql  = 'C:\Program Files\MySQL\MySQL Server 8.0\bin\mysql.exe'
$db     = 'clinical_trial_tracking'

function New-Password([int]$length = 24) {
    $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'.ToCharArray()
    $rng = [System.Security.Cryptography.RNGCryptoServiceProvider]::new()
    $out = New-Object System.Text.StringBuilder
    $buf = New-Object byte[] 1
    while ($out.Length -lt $length) {
        $rng.GetBytes($buf)
        # Rejection sampling: drop bytes that would bias the modulo.
        if ($buf[0] -lt (256 - (256 % $chars.Length))) {
            [void]$out.Append($chars[$buf[0] % $chars.Length])
        }
    }
    $rng.Dispose()
    return $out.ToString()
}

$pw = @{ auth = New-Password; admin = New-Password; reader = New-Password }

$sql = @"
CREATE USER IF NOT EXISTS 'app_auth'@'localhost'   IDENTIFIED BY '$($pw.auth)';
CREATE USER IF NOT EXISTS 'app_admin'@'localhost'  IDENTIFIED BY '$($pw.admin)';
CREATE USER IF NOT EXISTS 'app_reader'@'localhost' IDENTIFIED BY '$($pw.reader)';
ALTER USER 'app_auth'@'localhost'   IDENTIFIED BY '$($pw.auth)';
ALTER USER 'app_admin'@'localhost'  IDENTIFIED BY '$($pw.admin)';
ALTER USER 'app_reader'@'localhost' IDENTIFIED BY '$($pw.reader)';

-- app_auth: just enough to log people in and write audit rows
GRANT SELECT ON $db.AppUser TO 'app_auth'@'localhost';
GRANT UPDATE (last_login_at) ON $db.AppUser TO 'app_auth'@'localhost';
GRANT EXECUTE ON PROCEDURE $db.sp_audit TO 'app_auth'@'localhost';

GRANT 'ctt_admin'  TO 'app_admin'@'localhost';
GRANT 'ctt_reader' TO 'app_reader'@'localhost';
SET DEFAULT ROLE ALL TO 'app_admin'@'localhost', 'app_reader'@'localhost';
"@

$sql | & $mysql "--login-path=$LoginPath"
if ($LASTEXITCODE -ne 0) { throw "mysql.exe failed (exit $LASTEXITCODE)" }

$configDir = Join-Path $phase5 'app\config'
New-Item -ItemType Directory -Force -Path $configDir | Out-Null
$phase5Php = $phase5.Replace('\', '/')

$config = @"
<?php
// GENERATED by scripts\setup_app_accounts.ps1 -- do not edit, do not share.
// Lives outside the web root (app\public), so Apache never serves it.
return [
    'db' => ['host' => 'localhost', 'port' => 3306, 'name' => '$db'],
    'accounts' => [
        'auth'   => ['user' => 'app_auth',   'pass' => '$($pw.auth)'],
        'Admin'  => ['user' => 'app_admin',  'pass' => '$($pw.admin)'],
        'User'   => ['user' => 'app_reader', 'pass' => '$($pw.reader)'],
    ],
    'phase5_root' => '$phase5Php',
];
"@
# UTF-8 without BOM: a BOM before <?php would be sent as output and break headers.
[System.IO.File]::WriteAllText((Join-Path $configDir 'config.php'), $config, (New-Object System.Text.UTF8Encoding($false)))

Write-Host "App accounts ready: app_auth, app_admin (ctt_admin), app_reader (ctt_reader)."
Write-Host "Passwords written to app\config\config.php (not shown)."
